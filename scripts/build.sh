#!/usr/bin/env bash
#
# Build everything grassy-terrain needs. Run inside the Nix dev shell:
#
#     nix develop -c scripts/build.sh
#
# or use the top-level ./build.sh which enters the shell for you.
#
# Steps:
#   1. Build libghostty-vt from ~/source/ghostty into vendor/ghostty.
#   2. Build Jaylib from ~/source/jaylib and stage jaylib.so in vendor/jaylib.
#   3. Build the Janet native binding module (build/ghostty.so).
#   4. Write the build/gt launcher.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

GHOSTTY_SRC="${GHOSTTY_SRC:-$HOME/source/ghostty}"
JAYLIB_SRC="${JAYLIB_SRC:-$HOME/source/jaylib}"

echo "==> grassy-terrain root: $ROOT"

# --- 1. libghostty-vt ------------------------------------------------------
if [ ! -f "$ROOT/vendor/ghostty/lib/libghostty-vt.so" ]; then
  echo "==> building libghostty-vt (ReleaseFast)"
  if ! command -v zig >/dev/null 2>&1; then
    echo "error: zig not found; run inside 'nix develop'" >&2
    exit 1
  fi
  mkdir -p "$ROOT/vendor/ghostty"
  ( cd "$GHOSTTY_SRC" && zig build -Demit-lib-vt -Doptimize=ReleaseFast \
      --prefix "$ROOT/vendor/ghostty" )
else
  echo "==> libghostty-vt already built"
fi

# --- 2. Jaylib -------------------------------------------------------------
if [ ! -f "$ROOT/vendor/jaylib/jaylib.so" ]; then
  echo "==> building Jaylib"
  if [ ! -f "$JAYLIB_SRC/raylib/raylib.h" ]; then
    ( cd "$JAYLIB_SRC" && git submodule update --init --recursive )
  fi
  ( cd "$JAYLIB_SRC" && jpm build )
  mkdir -p "$ROOT/vendor/jaylib"
  cp "$JAYLIB_SRC/build/jaylib.so" "$ROOT/vendor/jaylib/jaylib.so"
else
  echo "==> Jaylib already staged"
fi

# --- 3. Janet native module ------------------------------------------------
echo "==> building ghostty Janet module"
jpm build

# --- 4. Launcher -----------------------------------------------------------
# Embed the exact Janet used to build the modules so the launcher works
# outside the dev shell too (nix store binaries carry their own rpaths).
JANET_BIN="$(command -v janet)"
cat > "$ROOT/build/gt" <<LAUNCHER
#!/bin/sh
# Generated by scripts/build.sh - do not edit.
ROOT="\$(cd "\$(dirname "\$0")/.." && pwd)"
export GRASSY_ROOT="\$ROOT"
export GRASSY_JAYLIB="\$ROOT/vendor/jaylib/jaylib.so"
export JANET_PATH="\$ROOT/build:\$ROOT/vendor/jaylib:\${JANET_PATH:-}"
export LD_LIBRARY_PATH="\$ROOT/vendor/ghostty/lib:\${LD_LIBRARY_PATH:-}"
JANET="$JANET_BIN"
[ -x "\$JANET" ] || JANET=janet
exec "\$JANET" "\$ROOT/main.janet" "\$@"
LAUNCHER
chmod +x "$ROOT/build/gt"

echo "==> done. Run ./build/gt"
